
#ifndef H_STL_MESH_IO
#define H_STL_MESH_IO

#pragma once

#include <string>
#include <vector>

#include "CPoint3.h"
#include "MathAlgorithms.h"

namespace ggeomlib
{
	/**
	* @brief Saves a list of triangles to an STL file in binary format.
	*
	* Each group of three consecutive vertices in the input list is treated as a single triangle.
	* Vertices must be ordered counter-clockwise (CCW) for each triangle.
	* Note: vertices are not shared — each triangle has its own set of 3 unique vertices.
	*
	* @param f_path			The full file path where the STL file will be saved.
	* @param f_tri_vertexes A flat list of triangle vertices (3 per triangle, ordered CCW).
	* @return				true if the file was successfully written, false otherwise.
	*/
	inline bool SaveTrianglesToSTL(const std::string& f_path, const std::vector<CPoint3>& f_tri_vertexes)
	{
		assert((f_tri_vertexes.size() % 3) == 0);

		std::ofstream l_out_file(f_path, std::ios::binary);
		if (!l_out_file.is_open())
		{
			return false;
		}
		const char l_header[80] = "Re-Triangulated Surface (Generated by MillingSimulatorPrototype)";
		l_out_file.write(l_header, sizeof(l_header));

		uint32_t l_tri_count = static_cast<uint32_t>(f_tri_vertexes.size() / 3);
		l_out_file.write(reinterpret_cast<const char*>(&l_tri_count), sizeof(l_tri_count));

		for (auto l_ivert = 0; l_ivert < f_tri_vertexes.size(); l_ivert++)
		{
			if (((l_ivert + 1) % 3) == 0)
			{
				const CPoint3 l_tri_normal = Cross((f_tri_vertexes[l_ivert - 2] - f_tri_vertexes[l_ivert - 1]),
											 (f_tri_vertexes[l_ivert - 2] - f_tri_vertexes[l_ivert])).GetUnitVector();

				if (!math_algs::IsVectorFinite(f_tri_vertexes[l_ivert - 2]) ||
					!math_algs::IsVectorFinite(f_tri_vertexes[l_ivert - 1]) ||
					!math_algs::IsVectorFinite(f_tri_vertexes[l_ivert]))
				{
					l_tri_count--;
					continue;
				}


				float l_norm_x = (float)l_tri_normal.m_x;
				float l_norm_y = (float)l_tri_normal.m_y;
				float l_norm_z = (float)l_tri_normal.m_z;
				l_out_file.write((const char*)(&l_norm_x), 4);
				l_out_file.write((const char*)(&l_norm_y), 4);
				l_out_file.write((const char*)(&l_norm_z), 4);

				float l_v1_x = (float)f_tri_vertexes[l_ivert - 2].m_x;
				float l_v1_y = (float)f_tri_vertexes[l_ivert - 2].m_y;
				float l_v1_z = (float)f_tri_vertexes[l_ivert - 2].m_z;
				l_out_file.write((const char*)(&l_v1_x), 4);
				l_out_file.write((const char*)(&l_v1_y), 4);
				l_out_file.write((const char*)(&l_v1_z), 4);

				float l_v2_x = (float)f_tri_vertexes[l_ivert - 1].m_x;
				float l_v2_y = (float)f_tri_vertexes[l_ivert - 1].m_y;
				float l_v2_z = (float)f_tri_vertexes[l_ivert - 1].m_z;
				l_out_file.write((const char*)(&l_v2_x), 4);
				l_out_file.write((const char*)(&l_v2_y), 4);
				l_out_file.write((const char*)(&l_v2_z), 4);

				float l_v3_x = (float)f_tri_vertexes[l_ivert].m_x;
				float l_v3_y = (float)f_tri_vertexes[l_ivert].m_y;
				float l_v3_z = (float)f_tri_vertexes[l_ivert].m_z;
				l_out_file.write((const char*)(&l_v3_x), 4);
				l_out_file.write((const char*)(&l_v3_y), 4);
				l_out_file.write((const char*)(&l_v3_z), 4);

				uint16_t l_attr = 0;
				l_out_file.write((const char*)(&l_attr), 2);

			}
		}

		l_out_file.close();
		return true;
	}
}

#endif
